def _safe_cta_http_url(url: Optional[str]) -> str:
    """Return http(s) CTA URLs only â€” Meta forbids tel: on cta_url."""
    raw = str(url or "").strip()
    if not raw:
        return ""
    lower = raw.lower()
    if lower.startswith("tel:"):
        return ""
    if not (lower.startswith("http://") or lower.startswith("https://")):
        return ""
    return raw


